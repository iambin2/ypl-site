// Bundles the battle function's code (supabase/functions/battle/server.mjs: the engine, the pinned @pkmn/sim, the bracket
// winner plan) into one file the
// battle function imports, so the deploy uploads plain code and Supabase never fetches the 100 MB+ @pkmn/mods package.
//
//   npm run build:battle      (run it before every deploy of the battle function; the bundle is not committed)
//
// The bundle is checked here on the spot: it must load, know both regulations and validate a team as the source does.
import { build } from "esbuild";
import { readFileSync, statSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { OLD_LEARNSETS, emptyFor } from "./oldLearnsets.mjs";

const ENTRY = fileURLToPath(new URL("../supabase/functions/battle/server.mjs", import.meta.url));
const OUT = fileURLToPath(new URL("../supabase/functions/battle/engine.bundle.mjs", import.meta.url));
const LICENSE = readFileSync(new URL("../node_modules/@pkmn/sim/LICENSE", import.meta.url), "utf8");

// Supabase refuses an upload this large (413 at 6.7 MB): the older generations' learnsets are left out (scripts/oldLearnsets.mjs).
// ponytail: a Champions species whose learnset ever inherits from an older generation would lose those moves here;
// the check at the bottom of this file and that comparison are what catch it.
const leaveOutOldLearnsets = {
  name: "leave-out-old-learnsets",
  setup(b) {
    b.onLoad({ filter: OLD_LEARNSETS }, args => ({ contents: emptyFor(args.path), loader: "js" }));
  },
};

await build({
  entryPoints: [ENTRY],
  outfile: OUT,
  bundle: true,
  format: "esm",
  platform: "neutral",
  mainFields: ["module", "main"],
  minify: true,
  // the simulator reads some class and function names at run time, so minifying keeps them
  keepNames: true,
  legalComments: "none",
  // Pokémon Showdown is MIT: its notice travels with the code.
  banner: { js: `/* Battle engine: Pokémon Showdown via @pkmn/sim and @pkmn/mods. Generated by scripts/build-battle-engine.mjs; do not edit.\n${LICENSE}*/` },
  logLevel: "warning",
  plugins: [leaveOutOldLearnsets],
});

const engine = await import(pathToFileURL(OUT).href + `?t=${Date.now()}`);
const formatid = engine.formatId("m-c", "doubles");
const problems = engine.validateTeam(formatid, [{ species: "Incineroar", item: "Sitrus Berry", ability: "Intimidate", moves: ["Knock Off"], nature: "Adamant", evs: {}, level: 50 }]);
const set = (species, item, ability, moves, nature) => ({ species, item, ability, moves, nature, evs: { hp: 2, atk: 32, spe: 32 }, level: 50 });
const legal = [
  set("Charizard-Mega-Y", "Charizardite Y", "Blaze", ["Heat Wave", "Air Slash", "Solar Beam", "Protect"], "Timid"),
  set("Garchomp", "Choice Scarf", "Rough Skin", ["Earthquake", "Dragon Claw", "Rock Slide", "Protect"], "Jolly"),
  set("Incineroar", "Sitrus Berry", "Intimidate", ["Fake Out", "Flare Blitz", "Throat Chop", "Parting Shot"], "Adamant"),
  set("Rotom-Wash", "Leftovers", "Levitate", ["Hydro Pump", "Thunderbolt", "Will-O-Wisp", "Protect"], "Modest"),
  set("Kingambit", "Black Glasses", "Defiant", ["Kowtow Cleave", "Sucker Punch", "Iron Head", "Protect"], "Adamant"),
  set("Sinistcha", "Mental Herb", "Hospitality", ["Matcha Gotcha", "Rage Powder", "Trick Room", "Strength Sap"], "Relaxed"),
];
if (!problems?.some(p => /Knock Off/.test(p)) || engine.validateTeam(formatid, legal) !== null || engine.formatId("m-b", "singles") !== "gen9championsbssregmb") {
  throw new Error("the bundle does not behave as the engine");
}
console.log(`${OUT}: ${(statSync(OUT).size / 1024 / 1024).toFixed(1)} MB, ${engine.ENGINE}`);
